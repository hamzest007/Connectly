import cors from 'cors';
import express from 'express';
import helmet from 'helmet';
import {env} from './config/env';
import {errorHandler, ok} from './common/http';
import rateLimit from 'express-rate-limit';
import morgan from 'morgan';
import authRoutes from './modules/auth/auth.routes';
import postRoutes from './modules/posts/post.routes';
import friendRoutes from './modules/friends/friend.routes';
import userRoutes from './modules/users/user.routes';
import notificationRoutes from './modules/notifications/notification.routes';
import uploadRoutes from './modules/uploads/upload.routes';
import reportRoutes from './modules/reports/report.routes';
import blockRoutes from './modules/blocks/block.routes';
import followRoutes from './modules/friends/follow.routes';
import adminRoutes from './modules/admin/admin.routes';
import storyRoutes from './modules/stories/story.routes';
import searchRoutes from './modules/search/search.routes';
import conversationRoutes from './modules/conversations/conversation.routes';
import groupRoutes from './modules/groups/group.routes';
import marketplaceRoutes from './modules/marketplace/marketplace.routes';
import platformRoutes from './modules/platform/platform.routes';
import eventRoutes from './modules/events/event.routes';
import creatorIdeaRoutes from './modules/creator-ideas/creator-idea.routes';

export const app = express();
app.use(helmet());
app.use(cors({origin: (origin, callback) => callback(null, !origin || env.clientOrigins.includes(origin)), credentials: true}));
app.use(express.json({limit: '1mb'}));
app.use(morgan(env.nodeEnv === 'production' ? 'combined' : 'dev'));
app.use(rateLimit({windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: true, legacyHeaders: false}));
app.get('/health', (_req, res) => ok(res, {service: 'connectly-api', status: 'ok', environment: env.nodeEnv}));
app.use('/api/v1/auth', authRoutes);
app.use('/api/v1/posts', postRoutes);
app.use('/api/v1/stories', storyRoutes);
app.use('/api/v1/search', searchRoutes);
app.use('/api/v1/conversations', conversationRoutes);
app.use('/api/v1/groups', groupRoutes);
app.use('/api/v1/marketplace', marketplaceRoutes);
app.use('/api/v1/platform', platformRoutes);
app.use('/api/v1/events', eventRoutes);
app.use('/api/v1/creator-ideas', creatorIdeaRoutes);
app.use('/api/v1/friends', friendRoutes);
app.use('/api/v1/users', userRoutes);
app.use('/api/v1/notifications', notificationRoutes);
app.use('/api/v1/uploads', uploadRoutes);
app.use('/api/v1/reports', reportRoutes);
app.use('/api/v1/blocks', blockRoutes);
app.use('/api/v1/follows', followRoutes);
app.use('/api/v1/admin', adminRoutes);
app.use(errorHandler);
