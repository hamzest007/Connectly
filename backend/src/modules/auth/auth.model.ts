import {Schema, model} from 'mongoose';

const userSchema = new Schema({
  email: {type: String, required: true, unique: true, lowercase: true, trim: true, index: true},
  normalizedEmail: {type: String, required: true, unique: true, lowercase: true, trim: true, index: true},
  phone: {type: String, default: '', trim: true, index: true},
  phoneNumber: {type: String, default: '', trim: true},
  username: {type: String, required: true, unique: true, lowercase: true, trim: true, index: true},
  normalizedUsername: {type: String, required: true, unique: true, lowercase: true, trim: true, index: true},
  accountType: {type: String, enum: ['user', 'page'], default: 'user', index: true},
  pageEnabled: {type: Boolean, default: false},
  pageName: {type: String, default: '', trim: true, maxlength: 80},
  pageUsername: {type: String, default: '', lowercase: true, trim: true, maxlength: 30},
  pageBio: {type: String, default: '', maxlength: 280},
  pageAvatarUrl: {type: String, default: ''},
  pageCoverUrl: {type: String, default: ''},
  pageCategory: {type: String, default: '', maxlength: 80},
  pageWebsite: {type: String, default: '', maxlength: 180},
  pageEmail: {type: String, default: '', lowercase: true, trim: true},
  pagePhone: {type: String, default: '', maxlength: 40},
  pageLocation: {type: String, default: '', maxlength: 120},
  pageCountry: {type: String, default: '', maxlength: 80},
  personalName: {type: String, default: ''},
  personalUsername: {type: String, default: ''},
  personalBio: {type: String, default: ''},
  personalAvatarUrl: {type: String, default: ''},
  personalCoverUrl: {type: String, default: ''},
  name: {type: String, required: true, trim: true, maxlength: 80},
  fullName: {type: String, default: '', trim: true, maxlength: 60},
  passwordHash: {type: String, required: true, select: false},
  bio: {type: String, default: '', maxlength: 280},
  avatarUrl: {type: String, default: ''},
  coverUrl: {type: String, default: ''},
  website: {type: String, default: '', maxlength: 180},
  location: {type: String, default: '', maxlength: 120},
  country: {type: String, default: '', maxlength: 80},
  education: {type: String, default: '', maxlength: 160},
  maritalStatus: {type: String, default: '', maxlength: 40},
  privateAccount: {type: Boolean, default: false},
  isVerified: {type: Boolean, default: false},
  emailVerified: {type: Boolean, default: false},
  twoFactorEnabled: {type: Boolean, default: false},
  e2eePublicKey: {type: String, default: '', maxlength: 200},
  deactivatedAt: {type: Date, default: null},
  verificationCodeHash: {type: String, default: ''},
  verificationExpiresAt: {type: Date, default: null},
  passwordResetHash: {type: String, default: ''},
  passwordResetExpiresAt: {type: Date, default: null},
  role: {type: String, enum: ['user', 'moderator', 'admin', 'super-admin', 'support-agent', 'analyst', 'finance-manager', 'developer-ops'], default: 'user', index: true},
  status: {type: String, enum: ['active', 'suspended'], default: 'active', index: true},
  accountStatus: {type: String, enum: ['active', 'pending-verification', 'disabled'], default: 'active', index: true},
  acceptedTermsAt: {type: Date, default: null},
  acceptedTermsVersion: {type: String, default: ''},
  suspendedUntil: {type: Date, default: null},
  suspensionReason: {type: String, default: '', maxlength: 500},
  theme: {type: String, enum: ['light','dark','system'], default: 'system'},
  accentColor: {type: String, default: '#635BFF'},
  profileLayout: {type: String, enum: ['standard','compact','featured'], default: 'standard'},
  featuredSections: {type: [String], default: []},
  interests: {type: [String], default: []},
  lastSeenAt: {type: Date, default: null, index: true},
}, {timestamps: true});

const refreshTokenSchema = new Schema({
  userId: {type: Schema.Types.ObjectId, ref: 'User', required: true, index: true},
  tokenHash: {type: String, required: true},
  expiresAt: {type: Date, required: true, index: {expires: 0}},
}, {timestamps: true});

export const User = model('User', userSchema);
export const RefreshToken = model('RefreshToken', refreshTokenSchema);
const recommendationPreferencesSchema = new Schema({
  userId: {type: Schema.Types.ObjectId, ref: 'User', required: true, unique: true, index: true},
  chronological: {type: Boolean, default: false},
  showReasons: {type: Boolean, default: true},
  mutedKeywords: {type: [String], default: []},
}, {timestamps: true});
export const RecommendationPreferences = model('RecommendationPreferences', recommendationPreferencesSchema);
